@cli.command()
@click.option("--port", default=8000, type=int, help="Port of the running CortexHeal server.")
@click.option("--json", "as_json", is_flag=True, help="Output as JSON.")
def status(port, as_json):
    """Health check against the running CortexHeal instance."""

    import urllib.request
    import json

    endpoints = {
        "health": "http://127.0.0.1:{}/health".format(port),
        "readiness": "http://127.0.0.1:{}/readiness".format(port),
    }

    results = {}
    for name, url in endpoints.items():
        try:
            req = urllib.request.Request(url, method="GET")
            with urllib.request.urlopen(req, timeout=5) as resp:
                data = json.loads(resp.read().decode())
                results[name] = data
        except Exception as e:
            results[name] = {"status": "UNREACHABLE", "error": str(e)}

    if as_json:
        click.echo(json.dumps(results, indent=2))
        return

    click.echo()
    health = results.get("health", {})
    readiness = results.get("readiness", {})

    health_status = health.get("status", "UNREACHABLE")
    readiness_status = readiness.get("status", "UNREACHABLE")

    color_map = {
        "HEALTHY": "green",
        "DEGRADED": "yellow",
        "NOT_READY": "red",
        "UNREACHABLE": "red",
    }

    click.secho("  Health:    {}".format(health_status), fg=color_map.get(health_status, "white"))
    click.secho("  Readiness: {}".format(readiness_status), fg=color_map.get(readiness_status, "white"))

    if readiness_status not in ("HEALTHY",):
        reason = readiness.get("reason", readiness.get("error", ""))
        if reason:
            click.echo("  Reason:    {}".format(reason))

    click.echo("  Server:    http://127.0.0.1:{}".format(port))
    click.echo("  Dashboard: http://127.0.0.1:{}".format(port))
    click.echo("  API Docs:  http://127.0.0.1:{}/docs".format(port))
    click.echo()

    if health_status == "UNREACHABLE":
        raise SystemExit(1)



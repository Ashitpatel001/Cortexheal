def _find_docker_compose_file():
    """Locate docker-compose.yml relative to the installed package."""
    candidates = [
        os.path.join(os.getcwd(), "docker-compose.yml"),
        os.path.join(PROJECT_ROOT, "docker-compose.yml"),
    ]
    for path in candidates:
        if os.path.isfile(path):
            return path
    return None


def _docker_available():
    """Check whether docker CLI is reachable."""
    try:
        r = subprocess.run(
            ["docker", "info"],
            capture_output=True, timeout=10,
        )
        return r.returncode == 0
    except Exception:
        return False


def _wait_for_postgres(database_url, timeout=30):
    """Block until PostgreSQL accepts connections or timeout."""
    import psycopg2
    deadline = time.time() + timeout
    while time.time() < deadline:
        try:
            conn = psycopg2.connect(database_url)
            conn.close()
            return True
        except Exception:
            time.sleep(1)
    return False


def _server_healthy(port=8000):
    """Quick GET /health check against the running server."""
    import urllib.request
    try:
        url = "http://127.0.0.1:{}/health".format(port)
        req = urllib.request.Request(url, method="GET")
        with urllib.request.urlopen(req, timeout=3) as resp:
            return resp.status == 200
    except Exception:
        return False



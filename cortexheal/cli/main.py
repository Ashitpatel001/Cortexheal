@cli.command()
@click.argument("run_id")
def debug(run_id):
    """Inspect a specific run's event timeline (legacy debug utility)."""
    from cortexheal.storage.postgres import get_run, get_events_for_run

    run = get_run(run_id)
    if not run:
        click.secho("Run {} not found.".format(run_id), fg="red")
        raise SystemExit(1)

    click.echo("RUN {} | Agent: {} | Status: {}".format(run.run_id, run.agent_id, run.status))
    click.echo("Start: {} | End: {}".format(run.start_time, run.end_time))
    click.echo("-" * 50)

    events = get_events_for_run(run_id)
    for event in events:
        tokens_info = " | Tokens: {}".format(event.tokens.total) if event.tokens and event.tokens.total > 0 else ""
        latency_info = " | {}ms".format(event.latency_ms) if event.latency_ms else ""
        tool_info = " {}".format(event.tool) if event.tool else ""
        click.echo("{} {}{}[{}]{}{}".format(
            event.sequence_number, event.event_type, tool_info, event.status, latency_info, tokens_info
        ))



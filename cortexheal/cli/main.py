@cli.command()
@click.option("--port", default=8000, type=int, help="Port to run the server on.")
@click.option("--host", default="0.0.0.0", help="Host to bind to.")
@click.option("--reload", "use_reload", is_flag=True, help="Enable auto-reload for development.")
@click.option("--workers", default=1, type=int, help="Number of Uvicorn workers.")
def start(port, host, use_reload, workers):
    """Start the CortexHeal backend server."""

    click.secho("\n  Starting CortexHeal server on http://{}:{} ...\n".format(host, port), fg="cyan")

    import uvicorn
    uvicorn.run(
        "cortexheal.server.api:app",
        host=host,
        port=port,
        reload=use_reload,
        workers=workers,
        log_level="info",
    )



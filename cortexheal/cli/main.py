@cli.command()
@click.option("--skip-docker", is_flag=True, help="Skip Docker/Postgres startup (use existing database).")
@click.option("--db-url", default=None, help="Override DATABASE_URL instead of using the default.")
def init(skip_docker, db_url):
    """Set up environment, start Postgres, run migrations, create first API key."""

    click.secho("\n  =================================================", fg="cyan")
    click.secho("       CortexHeal -- First-Time Setup              ", fg="cyan")
    click.secho("  =================================================\n", fg="cyan")

    # --- 1. Create .env -----------------------------------------------------------
    env_path = os.path.join(os.getcwd(), ".env")
    if os.path.isfile(env_path):
        click.secho("  [OK] .env already exists -- skipping creation.", fg="yellow")
    else:
        contents = ENV_TEMPLATE
        if db_url:
            contents = contents.replace(
                "DATABASE_URL=postgresql://cortexheal:cortexpassword@localhost:5433/cortexheal_db",
                "DATABASE_URL={}".format(db_url),
            )
        with open(env_path, "w") as f:
            f.write(contents)
        click.secho("  [OK] Created .env with default configuration.", fg="green")

    # Reload settings from the newly-created .env
    os.environ.setdefault("DATABASE_URL", db_url or "postgresql://cortexheal:cortexpassword@localhost:5433/cortexheal_db")

    database_url = db_url or os.environ.get(
        "DATABASE_URL",
        "postgresql://cortexheal:cortexpassword@localhost:5433/cortexheal_db",
    )

    # --- 2. Start Postgres via Docker Compose -------------------------------------
    if not skip_docker:
        compose_file = _find_docker_compose_file()
        if compose_file and _docker_available():
            click.echo("  -> Starting PostgreSQL via Docker Compose...")
            compose_dir = os.path.dirname(compose_file)
            result = subprocess.run(
                ["docker", "compose", "up", "-d"],
                cwd=compose_dir,
                capture_output=True, text=True, timeout=60,
            )
            if result.returncode == 0:
                click.secho("  [OK] PostgreSQL container started.", fg="green")
            else:
                click.secho("  [FAIL] Docker Compose failed: {}".format(result.stderr.strip()), fg="red")
                click.echo("    You can start Postgres manually and re-run with --skip-docker.")
                raise SystemExit(1)
        elif not _docker_available():
            click.secho("  [WARN] Docker not found -- skipping container start.", fg="yellow")
            click.echo("    Ensure PostgreSQL is running and DATABASE_URL is correct in .env.")
        else:
            click.secho("  [WARN] docker-compose.yml not found -- skipping container start.", fg="yellow")
    else:
        click.secho("  -> Skipping Docker startup (--skip-docker).", fg="yellow")

    # --- 3. Wait for Postgres -----------------------------------------------------
    click.echo("  -> Waiting for PostgreSQL to accept connections...")
    if _wait_for_postgres(database_url, timeout=30):
        click.secho("  [OK] PostgreSQL is ready.", fg="green")
    else:
        click.secho("  [FAIL] Could not connect to PostgreSQL within 30s.", fg="red")
        click.echo("    DATABASE_URL: {}".format(database_url))
        raise SystemExit(1)

    # --- 4. Initialize schema (init_db) -------------------------------------------
    click.echo("  -> Creating database schema...")
    # Ensure the settings module picks up our DATABASE_URL
    os.environ["DATABASE_URL"] = database_url
    from cortexheal.storage.postgres import init_db
    init_db()
    click.secho("  [OK] Database schema initialized.", fg="green")

    # --- 5. Generate first ADMIN API key ------------------------------------------
    click.echo("  -> Generating your first ADMIN API key...")
    from cortexheal.models.auth import ApiKey, hash_key, generate_raw_key
    from cortexheal.storage.postgres import save_api_key

    raw_key = generate_raw_key("ADMIN")
    k_hash = hash_key(raw_key)
    prefix = raw_key[:16] + "..."
    api_key = ApiKey(
        key_hash=k_hash,
        key_prefix=prefix,
        name="CLI-generated Admin Key",
        org_id="default_org",
        role="ADMIN",
    )
    save_api_key(api_key)

    click.echo()
    click.secho("  +-------------------------------------------------------------------+", fg="green")
    click.secho("  |  Your ADMIN API Key (shown once -- save it now):                   |", fg="green")
    click.secho("  |  {}  |".format(raw_key.ljust(60)), fg="green", bold=True)
    click.secho("  +-------------------------------------------------------------------+", fg="green")
    click.echo()

    # --- 6. Summary ---------------------------------------------------------------
    port = int(os.environ.get("CORTEXHEAL_PORT", "8000"))
    click.secho("  Setup complete. Next steps:", fg="cyan")
    click.echo("    1. Start the server:      cortexheal start")
    click.echo("    2. Run a live demo:        cortexheal demo")
    click.echo("    3. Open the dashboard:     http://localhost:{}".format(port))
    click.echo("    4. Open the API docs:      http://localhost:{}/docs".format(port))
    click.echo("    5. Log in with your key:   {}...".format(raw_key[:20]))
    click.echo()


